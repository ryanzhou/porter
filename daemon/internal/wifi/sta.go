// STASpec is one station (upstream Wi-Fi client) to run.
type STASpec struct {
	Radio    string
	Iface    string
	Country  string
	Networks []config.WifiNetwork
	// Only5 limits which 5 and 6 GHz frequencies the station may use;
	// nil allows all of them. A radio that also carries the router's own
	// network can only follow the uplink onto channels an access point is
	// allowed on, which excludes the radar channels.
	Only5 []int
	// Shared says the radio carries the router's own network as well.
	// Every scan then interrupts that network for a moment, so looking
	// for a known network is done less eagerly.
	Shared bool
}

// scanCeiling is the longest the station goes between scans while it has
// nothing to connect to. A known network that comes into range is joined
// within this time.
func (s STASpec) scanCeiling() time.Duration {
	if s.Shared {
		return 2 * time.Minute
	}
	return 30 * time.Second
}

// STAStatus is the station's connection state.
type STAStatus struct {
	Radio string `json:"radio"`
	Iface string `json:"iface"`
	// State is "connected"; "connecting" while joining a particular
	// network; "scanning" while looking for one it knows; or
	// "disconnected".
	State  string `json:"state"`
	SSID   string `json:"ssid,omitempty"`
	BSSID  string `json:"bssid,omitempty"`
	Freq   int    `json:"freq,omitempty"`
	Signal int    `json:"signal,omitempty"`
	// Failed names a saved network that keeps being rejected, with the
	// reason ("wrong_password" or "rejected").
	Failed     string `json:"failed,omitempty"`
	FailReason string `json:"fail_reason,omitempty"`
}

type ScanResult struct {
	SSID     string `json:"ssid"`
	Signal   int    `json:"signal"`
	Freq     int    `json:"freq"`
	Security string `json:"security"` // "open", "psk", "sae", "enterprise", "wep"
}

// STA supervises one wpa_supplicant instance.
type STA struct {
	Log    *slog.Logger
	RunDir string
	// OnChange is called when the association state changes.
	OnChange func()

	mu       sync.Mutex
	spec     STASpec
	p        *proc.Proc
	conf     string
	failed   string
	failWhy  string
	scanDone chan struct{}

	// Band steering; see Steer.
	ids     map[string]netIDs // saved network name -> its blocks
	enabled map[int]bool      // blocks switched on in wpa_supplicant
	// liveSSID and liveFreq are the connection as Status last found it.
	liveSSID string
	liveFreq int
	band     map[string]string // the band settled on: "5" or "2.4"
	both     map[string]bool   // the network was last seen on both bands
	lastScan time.Time
	scanGap  time.Duration
}

// A saved network becomes two blocks in wpa_supplicant's configuration,
// one confined to 5 GHz and above and one to 2.4 GHz, of which at most
// one is switched on at a time. A hidden network cannot be seen before it
// is joined, so it gets a single unrestricted block that is always on.
type netIDs struct{ five, two, any int }

const (
	// A 5 GHz signal at least this strong is preferred over 2.4 GHz
	// however strong that is: it is faster, and it is clear of Bluetooth
	// and of the noise USB 3 makes around 2.4 GHz.
	steerOn = -72
	// Once on 5 GHz, stay until it is weaker than this.
	steerOff = -80
	// On 2.4 GHz for want of a good enough 5 GHz signal: look again this
	// often.
	steerRecheck = 5 * time.Minute
)

func is5(freq int) bool { return freq >= 4900 }

// freqLists returns the frequencies of the 5 GHz block and the 2.4 GHz
// block.
func freqLists(only5 []int) (five, two string) {
	var f5, f2 []string
	for f := 2412; f <= 2472; f += 5 {
		f2 = append(f2, strconv.Itoa(f))
	}
	f2 = append(f2, "2484")
	if only5 != nil {
		for _, f := range only5 {
			if is5(f) {
				f5 = append(f5, strconv.Itoa(f))
			}
		}
		return strings.Join(f5, " "), strings.Join(f2, " ")
	}
	for _, r := range [][2]int{{36, 64}, {100, 144}, {149, 177}} {
		for ch := r[0]; ch <= r[1]; ch += 4 {
			f5 = append(f5, strconv.Itoa(5000+5*ch))
		}
	}
	for ch := 1; ch <= 233; ch += 4 { // 6 GHz
		f5 = append(f5, strconv.Itoa(5950+5*ch))
	}
	return strings.Join(f5, " "), strings.Join(f2, " ")
}

func (s *STA) ctrlDir() string { return filepath.Join(s.RunDir, "wpa") }

func (s *STA) Spec() STASpec {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.spec
}

func wpaConf(spec STASpec, ctrlDir string) (string, map[string]netIDs) {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# generated by porterd")
	w("ctrl_interface=%s", ctrlDir)
	w("update_config=0")
	w("country=%s", spec.Country)
	w("ap_scan=1")
	w("pmf=1")
	w("sae_pwe=2")
	// Back off scanning while nothing known is in range: on a shared
	// radio every scan interrupts the access point.
	w("autoscan=exponential:3:%d", int(spec.scanCeiling()/time.Second))
	// What a scan found stays good for joining a little longer than the
	// default five seconds: on a shared radio the access point has to move
	// to the network's channel first, and a second scan would only delay
	// the connection further.
	w("scan_res_valid_for_connect=20")
	// What was seen is remembered for longer than the time between two
	// looks for a better band, or the band not in use would be forgotten
	// in between and the choice made on half the picture.
	w("bss_expiration_age=%d", int(2*steerRecheck/time.Second))
	five, two := freqLists(spec.Only5)
	next := 0
	block := func(n config.WifiNetwork, freqs string, off bool, priority int) int {
		w("network={")
		w("\tssid=%s", hex.EncodeToString([]byte(n.SSID)))
		if n.Hidden {
			w("\tscan_ssid=1")
		}
		if n.PSK == "" {
			w("\tkey_mgmt=NONE")
		} else {
			w("\tkey_mgmt=WPA-PSK WPA-PSK-SHA256 SAE")
			w("\tieee80211w=1")
			// The passphrase is 8-63 printable ASCII (validated); the
			// parser takes everything up to the last quote.
			w("\tpsk=\"%s\"", n.PSK)
		}
		if freqs != "" {
			w("\tfreq_list=%s", freqs)
		}
		if off {
			w("\tdisabled=1")
		}
		w("\tpriority=%d", priority)
		w("}")
		next++
		return next - 1
	}
	ids := map[string]netIDs{}
	for _, n := range spec.Networks {
		if n.Hidden {
			// A hidden network cannot be seen in a scan, so it has one
			// block for both bands. On a shared radio it is kept to the
			// channels the access point may use as well.
			freqs := ""
			if spec.Only5 != nil {
				freqs = strings.TrimSpace(five + " " + two)
			}
			ids[n.SSID] = netIDs{five: -1, two: -1, any: block(n, freqs, spec.Shared, 2*n.Priority)}
			continue
		}
		id := netIDs{any: -1, five: -1}
		if five != "" {
			id.five = block(n, five, true, 2*n.Priority+1)
		}
		id.two = block(n, two, true, 2*n.Priority)
		ids[n.SSID] = id
	}
	return b.String(), ids
}

// Start runs (or reconfigures) the station. changed reports that it was
// started or given a new configuration, either of which drops whatever
// connection it had.
func (s *STA) Start(spec STASpec) (changed bool, err error) {
	conf, ids := wpaConf(spec, s.ctrlDir())
	path := filepath.Join(s.RunDir, "wpa-"+spec.Iface+".conf")
	s.mu.Lock()
	same := s.p != nil && s.spec.Iface == spec.Iface
	unchanged := same && conf == s.conf
	s.spec = spec
	s.conf = conf
	if !unchanged {
		// Every block starts switched off again; Steer turns the right
		// ones back on.
		s.ids = ids
		s.enabled = map[int]bool{}
		s.lastScan, s.scanGap = time.Time{}, 0
	}
	s.mu.Unlock()
	if unchanged {
		return false, nil
	}
	if err := os.WriteFile(path, []byte(conf), 0o600); err != nil {
		return false, err
	}
	if same {
		s.mu.Lock()
		s.failed, s.failWhy = "", ""
		s.mu.Unlock()
		if _, err := s.cli("reconfigure"); err == nil {
			return true, nil
		}
	}
	s.Stop()
	p := &proc.Proc{
		Name: "wpa-" + spec.Iface, Log: s.Log,
		Argv:   []string{"wpa_supplicant", "-i", spec.Iface, "-D", "nl80211", "-c", path},
		OnLine: s.onLine,
		// It starts again by itself, from the file: every network
		// switched off once more, whatever was switched on before.
		OnExit: func(error) {
			s.mu.Lock()
			s.enabled = map[int]bool{}
			s.lastScan, s.scanGap = time.Time{}, 0
			s.mu.Unlock()
		},
	}
	s.mu.Lock()
	s.p = p
	s.spec = spec
	s.conf = conf
	s.mu.Unlock()
	p.Start()
	return true, nil
}

func (s *STA) Stop() {
	s.mu.Lock()
	p := s.p
	s.p = nil
	s.conf = ""
	s.mu.Unlock()
	if p != nil {
		p.Stop()
	}
}

// onLine watches wpa_supplicant's event stream.
func (s *STA) onLine(line string) {
	notify := false
	// The uplink coming and going is the first thing to look for when a
	// connection is unreliable, so it goes in the log as it happens.
	for _, event := range []string{"CTRL-EVENT-CONNECTED", "CTRL-EVENT-DISCONNECTED", "CTRL-EVENT-SSID-TEMP-DISABLED", "CTRL-EVENT-ASSOC-REJECT", "CTRL-EVENT-AUTH-REJECT", "CTRL-EVENT-BEACON-LOSS"} {
		if i := strings.Index(line, event); i >= 0 {
			s.Log.Info("upstream Wi-Fi", "if", s.Spec().Iface, "event", strings.TrimPrefix(line[i:], "CTRL-EVENT-"))
			break
		}
	}
	s.mu.Lock()
	switch {
	case strings.Contains(line, "CTRL-EVENT-CONNECTED"):
		s.failed, s.failWhy = "", ""
		notify = true
		// Power saving on an uplink costs latency and, on several
		// adapters, packets. A router is not on a battery.
		go tool(5*time.Second, "iw", "dev", s.spec.Iface, "set", "power_save", "off").Run()
	case strings.Contains(line, "CTRL-EVENT-DISCONNECTED"):
		notify = true
	case strings.Contains(line, "CTRL-EVENT-SSID-TEMP-DISABLED"):
		if i := strings.Index(line, `ssid="`); i >= 0 {
			rest := line[i+6:]
			if j := strings.Index(rest, `" auth_failures=`); j >= 0 {
				s.failed = unescapeSSID(rest[:j])
			}
		}
		s.failWhy = "rejected"
		if strings.Contains(line, "reason=WRONG_KEY") {
			s.failWhy = "wrong_password"
		}
		notify = true
	case strings.Contains(line, "CTRL-EVENT-SCAN-RESULTS"):
		if s.scanDone != nil {
			close(s.scanDone)
			s.scanDone = nil
		}
		// A known network may just have come into range: act on it now,
		// while the results are fresh enough to join from.
		notify = true
	}
	s.mu.Unlock()
	if notify && s.OnChange != nil {
		s.OnChange()
	}
}

func (s *STA) cli(args ...string) (string, error) {
	s.mu.Lock()
	iface := s.spec.Iface
	running := s.p != nil
	s.mu.Unlock()
	if !running {
		return "", errors.New("station is not running")
	}
	argv := append([]string{"-p", s.ctrlDir(), "-i", iface}, args...)
	out, err := tool(4*time.Second, "wpa_cli", argv...).Output()
	if err != nil {
		return "", err
	}
	res := strings.TrimSpace(string(out))
	if res == "FAIL" || strings.HasPrefix(res, "FAIL-") {
		return res, errors.New("wpa_supplicant: " + res)
	}
	return res, nil
}

func (s *STA) Status() STAStatus {
	s.mu.Lock()
	st := STAStatus{Radio: s.spec.Radio, Iface: s.spec.Iface, State: "disconnected", Failed: s.failed, FailReason: s.failWhy}
	s.mu.Unlock()
	out, err := s.cli("status")
	if err != nil {
		return st
	}
	kv := parseKV(out)
	switch kv["wpa_state"] {
	case "COMPLETED":
		st.State = "connected"
	case "AUTHENTICATING", "ASSOCIATING", "ASSOCIATED", "4WAY_HANDSHAKE", "GROUP_HANDSHAKE":
		st.State = "connecting"
	case "SCANNING":
		st.State = "scanning"
	}
	if st.State == "connected" || st.State == "connecting" {
		st.SSID = unescapeSSID(kv["ssid"])
		st.BSSID = kv["bssid"]
		st.Freq, _ = strconv.Atoi(kv["freq"])
	}
	s.mu.Lock()
	s.liveSSID, s.liveFreq = "", 0
	if st.State == "connected" {
		s.liveSSID, s.liveFreq = st.SSID, st.Freq
	}
	s.mu.Unlock()
	if st.State == "connected" {
		if sig, err := s.cli("signal_poll"); err == nil {
			st.Signal, _ = strconv.Atoi(parseKV(sig)["RSSI"])
		}
	}
	return st
}

// Scan returns what is in range, strongest first, one entry per network
// name. With wait it scans first and returns the new results; without, it
// returns what the last scan found at once and starts a new scan in the
// background, the results of which a later call will have.
func (s *STA) Scan(wait bool) ([]ScanResult, error) {
	done := make(chan struct{})
	s.mu.Lock()
	if wait {
		s.scanDone = done
	}
	s.lastScan = time.Now()
	s.mu.Unlock()
	if _, err := s.cli("scan"); err != nil {
		// A scan may already be running; its results will do.
		if !strings.Contains(err.Error(), "FAIL-BUSY") {
			return nil, err
		}
	}
	if wait {
		select {
		case <-done:
		case <-time.After(12 * time.Second):
		}
	}
	out, err := s.cli("scan_results")
	if err != nil {
		return nil, err
	}
	return parseScanResults(out), nil
}

// KnownInRange returns the frequency the station will use for the saved
// network it is going to join, judged from the latest scan results
// without starting a scan.
func (s *STA) KnownInRange() (freq int, ok bool) {
	list, ok := s.look()
	if !ok {
		return 0, false
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	nets := append([]config.WifiNetwork(nil), s.spec.Networks...)
	sort.SliceStable(nets, func(i, j int) bool { return nets[i].Priority > nets[j].Priority })
	for _, n := range nets {
		if n.SSID == s.failed {
			// It has just turned the router away. The access point is not
			// moved for a network that cannot be joined.
			continue
		}
		sight := see(list, n.SSID, s.spec.Only5)
		switch {
		case n.Hidden && sight.any:
			return sight.freq, true
		case s.band[n.SSID] == "5" && sight.have5:
			return sight.freq5, true
		case s.band[n.SSID] == "2.4" && sight.have2:
			return sight.freq2, true
		}
	}
	return 0, false
}

// bss is one access point in the scan results.
type bss struct {
	SSID   string
	Freq   int
	Signal int
	Flags  string
}

func parseBSS(text string) []bss {
	var out []bss
	for _, line := range strings.Split(text, "\n") {
		f := strings.SplitN(line, "\t", 5)
		if len(f) < 5 || !strings.Contains(f[0], ":") {
			continue
		}
		ssid := unescapeSSID(f[4])
		if ssid == "" || strings.Trim(ssid, "\x00") == "" {
			continue
		}
		freq, _ := strconv.Atoi(f[1])
		sig, _ := strconv.Atoi(f[2])
		out = append(out, bss{SSID: ssid, Freq: freq, Signal: sig, Flags: f[3]})
	}
	return out
}

// sighting is what the scan results say about one network name: the
// strongest access point on each band.
type sighting struct {
	any, have5, have2     bool
	freq, freq5, freq2    int
	level, level5, level2 int
}

// see sums up the access points of one network. Access points on 5 GHz
// frequencies outside only5 (when it is set) do not count.
func see(list []bss, ssid string, only5 []int) sighting {
	var v sighting
	for _, b := range list {
		if b.SSID != ssid {
			continue
		}
		if is5(b.Freq) {
			if only5 != nil && !containsInt(only5, b.Freq) {
				continue
			}
			if !v.have5 || b.Signal > v.level5 {
				v.have5, v.freq5, v.level5 = true, b.Freq, b.Signal
			}
		} else if !v.have2 || b.Signal > v.level2 {
			v.have2, v.freq2, v.level2 = true, b.Freq, b.Signal
		}
		if !v.any || b.Signal > v.level {
			v.any, v.freq, v.level = true, b.Freq, b.Signal
		}
	}
	return v
}

func containsInt(list []int, v int) bool {
	for _, x := range list {
		if x == v {
			return true
		}
	}
	return false
}

// pickBand decides which band to use for a network seen as v, given the
// band in use so far ("" for none). The second result is false when the
// network is not in range and nothing can be decided.
func pickBand(v sighting, current string) (string, bool) {
	switch {
	case !v.have5 && !v.have2:
		return current, false
	case !v.have2:
		return "5", true
	case !v.have5:
		return "2.4", true
	}
	threshold := steerOn
	if current == "5" {
		threshold = steerOff
	}
	if v.level5 >= threshold {
		return "5", true
	}
	return "2.4", true
}

// look reads the latest scan results and settles, for every saved network
// in them, which band to use.
func (s *STA) look() ([]bss, bool) {
	out, err := s.cli("scan_results")
	if err != nil {
		return nil, false
	}
	list := parseBSS(out)
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.band == nil {
		s.band, s.both = map[string]string{}, map[string]bool{}
	}
	for _, n := range s.spec.Networks {
		if n.Hidden {
			continue
		}
		v := see(list, n.SSID, s.spec.Only5)
		band, inRange := pickBand(v, s.band[n.SSID])
		if !inRange {
			continue
		}
		s.both[n.SSID] = v.have5 && v.have2
		if s.spec.Shared && n.SSID == s.liveSSID && is5(s.liveFreq) && band != "5" {
			// On a shared radio a change of band takes the access point,
			// and every device on it, along. Up to 5 GHz that is worth
			// it. Down from a 5 GHz connection that still holds it is
			// not: if it really fails, it ends by itself.
			continue
		}
		if band != s.band[n.SSID] {
			s.Log.Info("upstream Wi-Fi band", "network", n.SSID, "band", band, "signal_5", v.level5, "signal_2.4", v.level2, "has_5", v.have5, "has_2.4", v.have2)
			s.band[n.SSID] = band
		}
	}
	return list, true
}

// Steer keeps the station on the better band. wpa_supplicant and the
// radio's firmware both choose mostly by signal strength, and 2.4 GHz is
// nearly always the stronger signal, so left alone the uplink ends up on
// the slower, noisier band even next to a perfectly good 5 GHz access
// point. Here the choice is made from the scan results instead: each
// saved network has a 5 GHz block and a 2.4 GHz block in wpa_supplicant,
// all switched off to begin with, and Steer switches on the one for the
// band chosen. Call it regularly.
//
// With hold, the station is kept quiet: every network is switched off
// and nothing is scanned for. The radio's access point is starting, and
// two things go wrong if the station is busy meanwhile. A station that
// tries to join a network before the access point is on that network's
// channel is refused, after which wpa_supplicant leaves the network alone
// for a while. And hostapd, which scans as it starts, cannot while the
// station scans; its way out is to take the access point's interface out
// of access point mode for the scan, which also takes it out of the
// router's bridge, where it does not return: a network devices can join
// and get nothing from.
func (s *STA) Steer(hold bool) {
	if _, ok := s.look(); !ok {
		return
	}
	type change struct {
		id int
		on bool
	}
	var off, on []change
	s.mu.Lock()
	for ssid, id := range s.ids {
		if id.any >= 0 {
			// A hidden network is on unless the station is to keep quiet.
			if s.spec.Shared && s.enabled[id.any] == hold {
				c := change{id.any, !hold}
				if hold {
					off = append(off, c)
				} else {
					on = append(on, c)
				}
			}
			continue
		}
		for _, want := range []change{{id.five, s.band[ssid] == "5" && !hold}, {id.two, s.band[ssid] == "2.4" && !hold}} {
			if want.id < 0 || s.enabled[want.id] == want.on {
				continue
			}
			if want.on {
				on = append(on, want)
			} else {
				off = append(off, want)
			}
		}
	}
	s.mu.Unlock()
	// Off before on: when the band changes under a live connection, the
	// station has to leave the old block before it will take the new one.
	for _, c := range append(off, on...) {
		cmd := "disable_network"
		if c.on {
			cmd = "enable_network"
		}
		if _, err := s.cli(cmd, strconv.Itoa(c.id)); err != nil {
			s.Log.Debug("steering", "cmd", cmd, "err", err)
			continue
		}
		s.mu.Lock()
		s.enabled[c.id] = c.on
		s.mu.Unlock()
	}

	if hold {
		return
	}
	// Scanning. With a block switched on, wpa_supplicant scans by itself
	// until it is connected. With none on (nothing known has been seen
	// yet) it sits idle, and while connected it never scans; those two
	// are for here.
	out, err := s.cli("status")
	if err != nil {
		return
	}
	kv := parseKV(out)
	now := time.Now()
	due := false
	s.mu.Lock()
	ceiling := s.spec.scanCeiling()
	switch kv["wpa_state"] {
	case "COMPLETED":
		s.scanGap = 0
		freq, _ := strconv.Atoi(kv["freq"])
		ssid := unescapeSSID(kv["ssid"])
		due = !is5(freq) && s.both[ssid] && now.Sub(s.lastScan) >= steerRecheck
	case "INACTIVE", "DISCONNECTED":
		if kv["wpa_state"] == "INACTIVE" {
			// Inactive means that no network is switched on. If the
			// record here says otherwise, the record is wrong (the
			// program restarted, or dropped the setting); forget it, and
			// the next pass switches them on again.
			for id, on := range s.enabled {
				if on {
					delete(s.enabled, id)
				}
			}
		}
		if s.scanGap == 0 {
			s.scanGap = 5 * time.Second
		}
		if now.Sub(s.lastScan) >= s.scanGap {
			due = true
			s.scanGap = min(2*s.scanGap, ceiling)
		}
	}
	if due {
		s.lastScan = now
	}
	s.mu.Unlock()
	if due {
		_, _ = s.cli("scan")
	}
}

func parseScanResults(text string) []ScanResult {
	best := map[string]ScanResult{}
	for _, b := range parseBSS(text) {
		r := ScanResult{SSID: b.SSID, Signal: b.Signal, Freq: b.Freq, Security: securityOf(b.Flags)}
		if cur, ok := best[b.SSID]; !ok || r.Signal > cur.Signal {
			best[b.SSID] = r
		}
	}
	out := make([]ScanResult, 0, len(best))
	for _, r := range best {
		out = append(out, r)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Signal != out[j].Signal {
			return out[i].Signal > out[j].Signal
		}
		return out[i].SSID < out[j].SSID
	})
	return out
}

func securityOf(flags string) string {
	switch {
	case strings.Contains(flags, "EAP"):
		return "enterprise"
	case strings.Contains(flags, "SAE") && !strings.Contains(flags, "PSK"):
		return "sae"
	case strings.Contains(flags, "PSK") || strings.Contains(flags, "SAE"):
		return "psk"
	case strings.Contains(flags, "WEP"):
		return "wep"
	}
	return "open"
}

func parseKV(text string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(text, "\n") {
		// Values are taken as they are: a network's name may end in a
		// space.
		if k, v, ok := strings.Cut(strings.TrimRight(line, "\r"), "="); ok {
			out[strings.TrimSpace(k)] = v
		}
	}
	return out
}

// unescapeSSID reverses wpa_supplicant's printf-style escaping.
func unescapeSSID(s string) string {
	if !strings.Contains(s, `\`) {
		return s
	}
	var b []byte
	for i := 0; i < len(s); i++ {
		if s[i] != '\\' || i+1 >= len(s) {
			b = append(b, s[i])
			continue
		}
		i++
		switch s[i] {
		case 'x':
			if i+2 < len(s) {
				if v, err := strconv.ParseUint(s[i+1:i+3], 16, 8); err == nil {
					b = append(b, byte(v))
					i += 2
					continue
				}
			}
			b = append(b, 'x')
		case 'n':
			b = append(b, '\n')
		case 'r':
			b = append(b, '\r')
		case 't':
			b = append(b, '\t')
		case 'e':
			b = append(b, 0x1b)
		default:
			b = append(b, s[i])
		}
	}
	return string(b)
}
